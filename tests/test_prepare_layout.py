import importlib.util
import json
from pathlib import Path
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("prepare_layout", ROOT / "scripts/prepare_layout.py")
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
CONFIG = json.loads((ROOT / "layout.json").read_text())


def raw_keymap():
    keys = [f"KC_{i}" for i in range(72)]
    keys[4] = "MT(MOD_RCTL, KC_DELETE)"
    keys[63:66] = ["KC_TRANSPARENT"] * 3
    return "// Generated by Oryx\r\n[1] = LAYOUT_moonlander(\r\n  " + ",  ".join(keys) + "\r\n),\r\n// Other functions stay intact.\r\n"


class PreparationTests(unittest.TestCase):
    def test_only_reserved_keys_change_and_nested_arguments_survive(self):
        source = raw_keymap()
        expected = source.replace(
            "KC_TRANSPARENT,  KC_TRANSPARENT,  KC_TRANSPARENT",
            "SOCD_LAST,  SOCD_UP,  SOCDTOG",
        )
        self.assertEqual(module.patch_keymap(source, CONFIG), expected)

    def test_reassigned_reserved_key_fails_instead_of_overwriting(self):
        with self.assertRaisesRegex(ValueError, "no longer blank"):
            module.patch_keymap(raw_keymap().replace("KC_TRANSPARENT", "KC_A", 1), CONFIG)

    def test_wrong_layout_shape_fails(self):
        with self.assertRaisesRegex(ValueError, "72 Moonlander keys"):
            module.patch_keymap(raw_keymap().replace("KC_71", "KC_71, KC_72"), CONFIG)

    def test_missing_gaming_layer_fails(self):
        with self.assertRaisesRegex(ValueError, "gaming layer"):
            module.patch_keymap(raw_keymap().replace("[1]", "[0]"), CONFIG)

    def test_old_custom_snapshot_is_rejected(self):
        with self.assertRaisesRegex(ValueError, "unmodified Oryx"):
            module.patch_keymap(raw_keymap() + "\nsocd_cleaner_t socd_opposing_pairs[2];", CONFIG)

    def test_preparation_keeps_oryx_source_and_existing_modules(self):
        with tempfile.TemporaryDirectory() as folder:
            source, destination = Path(folder) / "source", Path(folder) / "layout"
            source.mkdir()
            original = raw_keymap().encode()
            (source / "keymap.c").write_bytes(original)
            (source / "keymap.json").write_text('{"modules": ["zsa/defaults"]}')
            (source / "rules.mk").write_text("TAP_DANCE_ENABLE = yes\n")
            (source / "config.h").write_bytes(b"#define DEBOUNCE 1\r\n")
            module.prepare(source, destination, CONFIG)
            self.assertEqual((source / "keymap.c").read_bytes(), original)
            self.assertEqual((destination / "config.h").read_bytes(), (source / "config.h").read_bytes())
            self.assertEqual(json.loads((destination / "keymap.json").read_text())["modules"], ["zsa/defaults", "getreuer/socd_cleaner"])
            self.assertIn("SOCD_GAMING_LAYER=1", (destination / "rules.mk").read_text())


if __name__ == "__main__":
    unittest.main()
